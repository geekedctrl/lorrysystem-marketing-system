const fs = require('node:fs');
const assert = require('node:assert/strict');
const vm = require('node:vm');
const source = fs.readFileSync('dashboard/app/static/native.js', 'utf8');
const css = fs.readFileSync('dashboard/app/static/native.css', 'utf8');
const start = source.indexOf('  // Preview-only import:');
const end = source.indexOf('  async function loadSettings()', start);
assert(start !== -1 && end > start, 'Preview parser missing');
const code = source.slice(start, end);
const context = vm.createContext({URL});
const parse = vm.runInContext(`${code}\nparseImportPreview`, context);
const example = parse('company_name,website,industry\nAlpha,https://alpha.example,Logistics\nBeta,,Retail\nAlpha,https://alpha.example,Logistics');
assert.equal(example.valid, 1); assert.equal(example.invalid, 1); assert.equal(example.duplicate, 1);
assert.equal(parse('company_name,website,industry\nValid,https://example.com,SaaS').valid,1);
assert.match(parse('').error, /no rows/i);
assert.match(parse('a,b\nx,y').error, /header/i);
assert.match(parse('company_name,website,industry\nBad,"quoted,value",Retail').rows[0].issues[0], /malformed/i);
assert.match(parse('x'.repeat(12001)).error, /too large/i);
assert.match(parse('company_name,website,industry\nEvil,javascript:alert(1),Retail').rows[0].issues[0], /website/i);
assert(code.includes('esc(r.values.company_name') && code.includes('esc(r.values.website'), 'Imported data must be escaped');
assert(code.includes('disabled aria-describedby="import-disabled-help"'), 'Import must remain disabled');
assert(!/\bfetch\s*\(|\brequest\s*\(/.test(code), 'Preview must never call APIs');
assert(source.includes('epoch !== state.epoch') && source.includes('workspaceId !== state.workspace?.id'));
assert(css.includes('.import-table'));
console.log('Day 3 Import Preview synthetic tests passed: valid, missing, duplicate, empty, malformed, oversized, escaping, disabled commit, no API, workspace guard.');
